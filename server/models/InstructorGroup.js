const mongoose = require('mongoose');

const instructorGroupSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true
    },
    instructor: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    students: [{
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User'
    }],
    createdAt: {
        type: Date,
        default: Date.now
    }
}, { timestamps: true});
module.exports = mongoose.model('InstructorGroup', instructorGroupSchema);